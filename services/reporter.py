
from datetime import datetime
from pathlib import Path


def save_report(
    file_name: str,
    compiler_status: str,
    compiler_output: str,
    static_findings: list[str],
    pmd_status: str = "not_run",
    pmd_output: str = "",
    ai_review: str = "",
) -> Path:
    """Generate a structured Markdown report for JavaGuard AI."""

    project_dir = Path(__file__).resolve().parent.parent
    report_dir = project_dir / "reports"
    report_dir.mkdir(parents=True, exist_ok=True)

    generated_at = datetime.now()
    timestamp = generated_at.strftime("%Y%m%d_%H%M%S_%f")
    report_path = report_dir / f"report_{timestamp}.md"

    # Format static findings.
    if static_findings:
        findings_text = "\n".join(
            f"- {finding}" for finding in static_findings
        )
    else:
        findings_text = "No basic static findings were recorded."

    # Keep missing results distinguishable from successful analysis.
    compiler_text = (
        compiler_output.strip()
        if compiler_output and compiler_output.strip()
        else "No compiler diagnostics available."
    )

    pmd_text = (
        pmd_output.strip()
        if pmd_output and pmd_output.strip()
        else "No PMD output available."
    )

    ai_text = (
        ai_review.strip()
        if ai_review and ai_review.strip()
        else "AI review was not performed."
    )

    # Create the report.
    report_content = f"""# JavaGuard AI
## Java Code Analysis Report

---

### File Information

| Field | Details |
|---|---|
| Java file | `{file_name}` |
| Generated | {generated_at.strftime("%Y-%m-%d %H:%M:%S")} |
| Compiler status | **{compiler_status}** |
| PMD status | **{pmd_status}** |

---

## 1. Executive Summary

This report combines Java compiler diagnostics, basic static checks,
PMD code-quality analysis, and an AI-assisted code review.

**Important:** A successful compilation does not guarantee that a program
is logically correct or free of defects.

## 2. Java Compiler Analysis

**Status:** {compiler_status}

```text
{compiler_text}
```

## 3. Basic Static Checks

{findings_text}

## 4. PMD Code Quality Analysis

**Status:** {pmd_status}

```text
{pmd_text}
```

## 5. AI-Assisted Code Review

{ai_text}

## 6. Recommendations

- Review compiler errors before treating the Java source as valid.
- Verify each static-analysis finding against the source code.
- Treat AI findings as recommendations that require human review.
- Test suggested fixes before adopting them.
- Do not interpret missing or failed analysis output as a clean result.

## 7. Limitations

- Basic text-based checks may miss defects or report false positives.
- PMD results depend on the configured ruleset and successful execution.
- AI-generated explanations and fixes may be inaccurate.
- This report does not guarantee program correctness or security.

---

*Generated by JavaGuard AI — AI-Powered Java Code Review Assistant.*
"""

    report_path.write_text(report_content, encoding="utf-8")

    return report_path
